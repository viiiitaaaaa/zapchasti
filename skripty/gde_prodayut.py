import re

def _nums(s):
    return [int(re.sub(r"\D", "", p)) for p in re.split(r"[–-]", s or "") if re.sub(r"\D", "", p)]

def _rng(lo, hi):
    return _sp(lo) + (f"–{_sp(hi)}" if hi and hi != lo else "")

def _zrng(lo, hi):
    return str(lo) + (f"–{hi}" if hi and hi != lo else "")

def _a(url, name):
    return f'<a href="{url}" target="_blank">{name}</a>'

