def zz_cell(oe):
    if not oe:
        return '<span class="mute">нет номера</span>'
    if oe not in ZZAP:
        return '<span class="mute">—</span>'
    name, n1, r1, n2, r2 = ZZAP[oe]
    if n1 is None:
        return f'<span class="mute">{E(name)}</span>'
    a = f"в наличии: <b>{prod(n1)}</b>" + (f" · {r1} ₽" if n1 else "")
    b = f"под заказ: {prod(n2)}" + (f" · {r2} ₽" if n2 else "")
    return f"{a}<br><span class=\"mute\">{b}</span>"

def row(it):
    n, oe, name, car, v, note = it
    label, cls = VERDICT[v]
    note = NOTES_N.get(n, note)
    proof = ""
    if oe and os.path.exists(os.path.join(ROOT, f"dokazatelstva/zzap_{oe}.png")):
        proof = f'<a href="dokazatelstva/zzap_{oe}.png" data-big="dokazatelstva/zzap_{oe}.png">снимок</a> · <a href="{zz(oe)}" target="_blank">zzap</a>'
    elif oe:
        proof = f'<a href="{zz(oe)}" target="_blank">zzap</a>'
    return (f'<tr class="v-{cls}"><td>{n}</td><td>{foto(n)}</td><td><b>{E(name)}</b><br><span class="mono">{E(oe or "—")}</span> · {car}</td>'
            f'<td>{zz_cell(oe)}</td><td><span class="tag {cls}">{label}</span></td><td>{E(note)}</td><td class="nw">{proof}</td></tr>')

