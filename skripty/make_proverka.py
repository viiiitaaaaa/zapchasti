VERDICT = {
 "T": ("в тест", "t"), "Z": ("позже / под заказ", "z"), "D": ("добавка к заказу", "d"),
 "N": ("не брать / выяснить", "n"), "U": ("не проверяли", "u"),
}

def row_html(r):
    n, oe, name, car, price, offers, v, note = r
    label, cls = VERDICT[v]
    e = html.escape
    num = oe.split("-")[0]
    if v != "U" and num != "—":
        src = (f'<a href="https://emex.ru/products/{num}/Great%20Wall/10797" target="_blank">emex</a> · '
               f'<a href="https://www.zzap.ru/public/search.aspx#rawdata={num}&amp;class_man=GREAT%20WALL" target="_blank">zzap</a>')
    else:
        src = '<span class="mute">—</span>'
    return (f'<tr class="v-{cls}"><td>{n}</td><td class="mono">{e(oe)}</td><td>{e(name)}</td><td>{e(car)}</td>'
            f'<td>{e(price)}</td><td>{e(offers)}</td><td><span class="tag {cls}">{label}</span></td><td>{e(note)}</td>'
            f'<td style="white-space:nowrap">{src}</td></tr>')

counts = {k: sum(1 for r in ROWS if r[6] == k) for k in VERDICT}
table = "\n".join(row_html(r) for r in ROWS)

import os
tpl = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "proverka_tpl.html"), encoding="utf-8").read()
out = tpl.replace("{{TABLE}}", table)
for k, c in counts.items():
    out = out.replace("{{C_" + k + "}}", str(c))
