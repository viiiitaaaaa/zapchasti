def prod(k):
    """1 продавец, 2 продавца, 5 продавцов"""
    if k % 10 == 1 and k % 100 != 11: w = "продавец"
    elif 2 <= k % 10 <= 4 and not 12 <= k % 100 <= 14: w = "продавца"
    else: w = "продавцов"
    return f"{k} {w}"

